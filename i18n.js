  const listeners = new Set();
  let lang = 'es';
  function translate(str) { return lang === 'en' && Object.prototype.hasOwnProperty.call(translations, str) ? translations[str] : str; }
  function phrase(key, values = {}) {
    const found = dynamic[key];
    if (!found) throw new Error('Missing translation key: ' + key);
    return found[lang === 'en' ? 1 : 0].replace(/\{([a-z]+)\}/g, (_, name) => String(values[name] ?? ''));
  }
  function update() {
    const walker = document.createTreeWalker(document.documentElement, NodeFilter.SHOW_TEXT, {
      acceptNode(node) { return ['SCRIPT', 'STYLE'].includes(node.parentElement?.tagName) ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT; }
    });
    let node;
    while ((node = walker.nextNode())) {
      if (!originalNodes.has(node)) originalNodes.set(node, node.nodeValue);
      const source = originalNodes.get(node);
      const value = source.trim();
      if (value && Object.prototype.hasOwnProperty.call(translations, value)) {
        const start = source.indexOf(value);
        node.nodeValue = source.slice(0, start) + translate(value) + source.slice(start + value.length);
      }
    }
    document.querySelectorAll('*').forEach(el => {
      let original = originalAttrs.get(el);
      if (!original) { original = {}; originalAttrs.set(el, original); }
      for (const attr of attrNames) {
        if (!el.hasAttribute(attr)) continue;
        if (!(attr in original)) original[attr] = el.getAttribute(attr);
        const from = original[attr];
        if (Object.prototype.hasOwnProperty.call(translations, from)) el.setAttribute(attr, translate(from));
      }
    });
    const email = document.querySelector('a[href^="mailto:info@palletsure.com"]');
    if (email) email.href = 'mailto:info@palletsure.com?subject=' + encodeURIComponent(lang === 'en' ? 'FIXBOX calculator enquiry' : 'Consulta sobre simulador FIXBOX');
    document.documentElement.lang = lang;
    document.querySelectorAll('[data-lang]').forEach(button => {
      const isActive = button.dataset.lang === lang;
      button.setAttribute('aria-pressed', String(isActive));
      button.classList.toggle('active', isActive);
    });
  }
  function setLanguage(next, persist = true) {
    if (next !== 'es' && next !== 'en') return;
    lang = next;
    if (persist) { try { localStorage.setItem('palletsure-language', next); } catch (_) {} }
    update();
    listeners.forEach(fn => fn(lang));
  }
  function onChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }
